import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const extractsDir = path.join(rootDir, 'data/raw/pdf-extracts');
const outPath = path.join(rootDir, 'src/data/examPresets.json');

// Remove noisy unused extracts that weren't selected as authorities
for (const unused of ['pan-3.txt', 'rpsc-advt-1.txt', 'rpsc-advt-2.txt', 'rpsc-advt-3.txt', 'bpsc-1.txt']) {
  const p = path.join(extractsDir, unused);
  if (fs.existsSync(p)) fs.unlinkSync(p);
}

const norm = (s) => s.replace(/\s+/g, ' ').trim();

function assertInExtract(extractRel, pageNum, quote) {
  const full = fs.readFileSync(path.join(rootDir, extractRel), 'utf8');
  const pageRegex = new RegExp(`--- Page ${pageNum} ---([\\s\\S]*?)(?=--- Page ${pageNum + 1} ---|$)`);
  const m = full.match(pageRegex);
  assert.ok(m, `Page ${pageNum} not found in ${extractRel}`);
  const pageText = norm(m[1]);
  const qNorm = norm(quote);
  assert.ok(pageText.includes(qNorm), `Quote NOT found verbatim on page ${pageNum} of ${extractRel}:\n  Quote: "${qNorm}"`);
}

